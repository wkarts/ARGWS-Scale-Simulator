#!/usr/bin/env bash
set -euo pipefail

APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PID_FILE="$APP_DIR/scale-simulator.pid"
LOG_DIR="$APP_DIR/logs"
LOG_FILE="$LOG_DIR/scale-simulator.log"
ENV_FILE="$APP_DIR/.env"

mkdir -p "$LOG_DIR" "$APP_DIR/data"

set -a
[[ -f "$ENV_FILE" ]] && source "$ENV_FILE"
set +a

bool_true() {
  case "${1:-}" in
    1|true|TRUE|yes|YES|sim|SIM|on|ON) return 0 ;;
    *) return 1 ;;
  esac
}

BIN_PATH="${SCALE_SIMULATOR_BINARY:-$APP_DIR/bin/scale_simulator_tauri}"
if [[ "$BIN_PATH" != /* ]]; then
  BIN_PATH="$APP_DIR/${BIN_PATH#./}"
fi

if [[ -f "$PID_FILE" ]] && kill -0 "$(cat "$PID_FILE")" 2>/dev/null; then
  echo "Scale Simulator já está em execução. PID: $(cat "$PID_FILE")"
  exit 0
fi

if [[ ! -x "$BIN_PATH" ]]; then
  echo "Binário não encontrado ou sem permissão de execução: $BIN_PATH"
  echo "Execute: chmod +x $APP_DIR/bin/scale_simulator_tauri"
  exit 1
fi

PUBLISH_ALL_PORTS="${SCALE_SIMULATOR_PUBLISH_ALL_PORTS:-false}"
START_ALL_PORTS="${SCALE_SIMULATOR_START_ALL_PORTS:-false}"
RESPECT_CLOUDPANEL_PORT="${SCALE_SIMULATOR_RESPECT_CLOUDPANEL_PORT:-true}"
PUBLIC_BIND_HOST="${SCALE_SIMULATOR_PUBLIC_BIND_HOST:-0.0.0.0}"

if bool_true "$PUBLISH_ALL_PORTS"; then
  export SCALE_SIMULATOR_API_HOST="${SCALE_SIMULATOR_API_HOST:-$PUBLIC_BIND_HOST}"
  export SCALE_SIMULATOR_WEB_HOST="${SCALE_SIMULATOR_WEB_HOST:-$PUBLIC_BIND_HOST}"
  export SCALE_SIMULATOR_WEBHOOK_HOST="${SCALE_SIMULATOR_WEBHOOK_HOST:-$PUBLIC_BIND_HOST}"
  export SCALE_SIMULATOR_WEBSOCKET_HOST="${SCALE_SIMULATOR_WEBSOCKET_HOST:-$PUBLIC_BIND_HOST}"
  export SCALE_SIMULATOR_API_ALLOW_PUBLIC_NETWORK="${SCALE_SIMULATOR_API_ALLOW_PUBLIC_NETWORK:-true}"
  export SCALE_SIMULATOR_API_CORS="${SCALE_SIMULATOR_API_CORS:-true}"
  export SCALE_SIMULATOR_WEB_BIND_LAN="${SCALE_SIMULATOR_WEB_BIND_LAN:-true}"
  export SCALE_SIMULATOR_WEBHOOK_ALLOW_LAN="${SCALE_SIMULATOR_WEBHOOK_ALLOW_LAN:-true}"
  export SCALE_SIMULATOR_WEBHOOK_ALLOW_EXTERNAL="${SCALE_SIMULATOR_WEBHOOK_ALLOW_EXTERNAL:-true}"
  export SCALE_SIMULATOR_WEBSOCKET_ALLOW_LAN="${SCALE_SIMULATOR_WEBSOCKET_ALLOW_LAN:-true}"
  export SCALE_SIMULATOR_WEBSOCKET_ALLOW_EXTERNAL="${SCALE_SIMULATOR_WEBSOCKET_ALLOW_EXTERNAL:-true}"
fi

if bool_true "$START_ALL_PORTS"; then
  export SCALE_SIMULATOR_WEBHOOK_ENABLED=true
  export SCALE_SIMULATOR_WEBHOOK_AUTO_START=true
  export SCALE_SIMULATOR_WEBSOCKET_ENABLED=true
  export SCALE_SIMULATOR_WEBSOCKET_AUTO_START=true
  export SCALE_SIMULATOR_SERVICES_AUTO_START=true
fi

export SCALE_SIMULATOR_ENV_FILE="${SCALE_SIMULATOR_ENV_FILE:-$ENV_FILE}"
export SCALE_SIMULATOR_WEB_DIST_DIR="${SCALE_SIMULATOR_WEB_DIST_DIR:-$APP_DIR/dist}"
export SCALE_SIMULATOR_DATA_DIR="${SCALE_SIMULATOR_DATA_DIR:-$APP_DIR/data}"
export SCALE_SIMULATOR_LOGS_DIR="${SCALE_SIMULATOR_LOGS_DIR:-$LOG_DIR}"
export SCALE_SIMULATOR_API_HOST="${SCALE_SIMULATOR_API_HOST:-127.0.0.1}"
export SCALE_SIMULATOR_API_PORT="${SCALE_SIMULATOR_API_PORT:-61001}"
export SCALE_SIMULATOR_WEB_HOST="${SCALE_SIMULATOR_WEB_HOST:-127.0.0.1}"

if bool_true "$RESPECT_CLOUDPANEL_PORT" && [[ -n "${PORT:-}" ]]; then
  export SCALE_SIMULATOR_WEB_PORT="$PORT"
else
  export SCALE_SIMULATOR_WEB_PORT="${SCALE_SIMULATOR_WEB_PORT:-61002}"
fi

export SCALE_SIMULATOR_WEB_ENABLED="${SCALE_SIMULATOR_WEB_ENABLED:-true}"
export SCALE_SIMULATOR_WEB_AUTO_START="${SCALE_SIMULATOR_WEB_AUTO_START:-true}"
export SCALE_SIMULATOR_SERVICES_AUTO_START="${SCALE_SIMULATOR_SERVICES_AUTO_START:-true}"
export SCALE_SIMULATOR_WEBHOOK_HOST="${SCALE_SIMULATOR_WEBHOOK_HOST:-127.0.0.1}"
export SCALE_SIMULATOR_WEBHOOK_PORT="${SCALE_SIMULATOR_WEBHOOK_PORT:-61003}"
export SCALE_SIMULATOR_WEBSOCKET_HOST="${SCALE_SIMULATOR_WEBSOCKET_HOST:-127.0.0.1}"
export SCALE_SIMULATOR_WEBSOCKET_PORT="${SCALE_SIMULATOR_WEBSOCKET_PORT:-61004}"

ARGS=(
  --mode=headless-api
  --host "$SCALE_SIMULATOR_API_HOST"
  --port "$SCALE_SIMULATOR_API_PORT"
  --data-dir "$SCALE_SIMULATOR_DATA_DIR"
  --start-web-proxy
  --start-services
)

if [[ "${SCALE_SIMULATOR_WEBHOOK_ENABLED:-false}" == "true" ]]; then
  ARGS+=(--start-webhook)
fi

if [[ "${SCALE_SIMULATOR_WEBSOCKET_ENABLED:-false}" == "true" ]]; then
  ARGS+=(--start-websocket)
fi

cd "$APP_DIR"
nohup "$BIN_PATH" "${ARGS[@]}" >> "$LOG_FILE" 2>&1 &

echo $! > "$PID_FILE"
echo "Scale Simulator iniciado. PID: $(cat "$PID_FILE")"
echo "WebPort:  http://$SCALE_SIMULATOR_WEB_HOST:$SCALE_SIMULATOR_WEB_PORT"
echo "API:      http://$SCALE_SIMULATOR_API_HOST:$SCALE_SIMULATOR_API_PORT"
echo "Webhook:  http://$SCALE_SIMULATOR_WEBHOOK_HOST:$SCALE_SIMULATOR_WEBHOOK_PORT${SCALE_SIMULATOR_WEBHOOK_BASE_PATH:-/webhooks} (${SCALE_SIMULATOR_WEBHOOK_ENABLED:-false})"
echo "WebSocket: ws://$SCALE_SIMULATOR_WEBSOCKET_HOST:$SCALE_SIMULATOR_WEBSOCKET_PORT${SCALE_SIMULATOR_WEBSOCKET_PATH:-/ws} (${SCALE_SIMULATOR_WEBSOCKET_ENABLED:-false})"
echo "Logs:     $LOG_FILE"
