#!/usr/bin/env bash
set -euo pipefail
APP_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
set -a
[[ -f "$APP_DIR/.env" ]] && source "$APP_DIR/.env"
set +a

RESPECT_CLOUDPANEL_PORT="${SCALE_SIMULATOR_RESPECT_CLOUDPANEL_PORT:-true}"
WEB_PORT="${SCALE_SIMULATOR_WEB_PORT:-61002}"
if [[ "$RESPECT_CLOUDPANEL_PORT" =~ ^(1|true|TRUE|yes|YES|sim|SIM|on|ON)$ ]] && [[ -n "${PORT:-}" ]]; then
  WEB_PORT="$PORT"
fi

cat <<PORTS
Portas configuradas:

API Headless:
  Host: ${SCALE_SIMULATOR_API_HOST:-127.0.0.1}
  Porta: ${SCALE_SIMULATOR_API_PORT:-61001}
  URL: http://${SCALE_SIMULATOR_API_HOST:-127.0.0.1}:${SCALE_SIMULATOR_API_PORT:-61001}

Web / Browser / WebPort:
  Host: ${SCALE_SIMULATOR_WEB_HOST:-127.0.0.1}
  Porta: $WEB_PORT
  URL: http://${SCALE_SIMULATOR_WEB_HOST:-127.0.0.1}:$WEB_PORT

Webhook:
  Habilitado: ${SCALE_SIMULATOR_WEBHOOK_ENABLED:-false}
  Host: ${SCALE_SIMULATOR_WEBHOOK_HOST:-127.0.0.1}
  Porta: ${SCALE_SIMULATOR_WEBHOOK_PORT:-61003}
  URL: http://${SCALE_SIMULATOR_WEBHOOK_HOST:-127.0.0.1}:${SCALE_SIMULATOR_WEBHOOK_PORT:-61003}${SCALE_SIMULATOR_WEBHOOK_BASE_PATH:-/webhooks}

WebSocket:
  Habilitado: ${SCALE_SIMULATOR_WEBSOCKET_ENABLED:-false}
  Host: ${SCALE_SIMULATOR_WEBSOCKET_HOST:-127.0.0.1}
  Porta: ${SCALE_SIMULATOR_WEBSOCKET_PORT:-61004}
  URL: ws://${SCALE_SIMULATOR_WEBSOCKET_HOST:-127.0.0.1}:${SCALE_SIMULATOR_WEBSOCKET_PORT:-61004}${SCALE_SIMULATOR_WEBSOCKET_PATH:-/ws}

Publicar todas as portas: ${SCALE_SIMULATOR_PUBLISH_ALL_PORTS:-false}
Iniciar todas as portas: ${SCALE_SIMULATOR_START_ALL_PORTS:-false}
Respeitar PORT do CloudPanel: ${SCALE_SIMULATOR_RESPECT_CLOUDPANEL_PORT:-true}
PORTS
